#!/usr/bin/env python
"""Per-module parameter counts of the implemented model vs the manuscript's Supplementary Table 1.

Writes docs/parameter_accounting.md. The implementation follows the MAIN TEXT, so rows that exist
only in Supplementary Table 1 (CrossScaleAttention, per-band frequency projections) are shown as
absent here, and the totals differ accordingly. Counts come from instantiating the default model.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

from mars_tb.config import ModelConfig, load_model_config
from mars_tb.models.mars_tb import MARSTB

ROOT = Path(__file__).resolve().parents[1]


def n(module) -> int:
    return sum(p.numel() for p in module.parameters())


def collect(model: MARSTB) -> dict[str, int]:
    lora = sum(p.numel() for name, p in model.backbone.named_parameters() if "lora_" in name)
    return {
        "frozen_backbone": n(model.backbone) - lora,
        "lora": lora,
        "msvle_text_guidance": sum(n(g) for g in model.msvle.guidance),
        "msvle_scale_fusion": n(model.msvle.fuse) + n(model.msvle.norm),
        "msvle_prompt_embeddings": n(model.msvle.prompts),
        "ddfm_freq_band_cnn": sum(n(e) for e in model.ddfm.encoders),  # type: ignore[union-attr]
        "ddfm_cross_attention": n(model.ddfm.attn) + n(model.ddfm.norm),  # type: ignore[union-attr]
        "agrn_gat": sum(n(g) for g in (model.agrn.gat1, model.agrn.gat2, model.agrn.gat3))  # type: ignore[union-attr]
        + n(model.agrn.res1)
        + n(model.agrn.out3)
        + n(model.agrn.norm1)
        + n(model.agrn.norm2)
        + n(model.agrn.norm3),  # type: ignore[union-attr]
        "agrn_readout": n(model.agrn.readout) + n(model.agrn.readout_norm),  # type: ignore[union-attr]
        "agrn_node_classifier": n(model.agrn.node_head),  # type: ignore[union-attr]
        "prm": n(model.prm),  # type: ignore[arg-type]
        "mt_edl": n(model.head),
    }


SUPP_KEY = {
    "frozen_backbone": ("frozen_backbone", None),
    "lora": ("components", "lora"),
    "msvle_text_guidance": ("components", "msvle_text_guidance"),
    "msvle_scale_fusion": ("components", "msvle_scale_fusion"),
    "ddfm_freq_band_cnn": ("components", "ddfm_freq_band_cnn"),
    "ddfm_cross_attention": ("components", "ddfm_cross_attention"),
    "agrn_gat": ("components", "agrn_gat"),
    "agrn_readout": ("components", "agrn_readout"),
    "agrn_node_classifier": ("components", "agrn_node_classifier"),
    "prm": ("components", "prm"),
    "mt_edl": ("components", "mt_edl"),
}
ONLY_IN_SUPP = ("msvle_cross_scale_attention", "ddfm_freq_projection")


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--model-config", type=Path, default=ROOT / "configs" / "model" / "mars_tb.yaml")
    ap.add_argument("--out", type=Path, default=ROOT / "docs" / "parameter_accounting.md")
    args = ap.parse_args(argv)
    cfg: ModelConfig = load_model_config(args.model_config)
    counts = collect(MARSTB(cfg))
    supp = json.loads((ROOT / "reporting" / "manuscript_reported_values.json").read_text(encoding="utf-8"))[
        "supp_s1_parameters"
    ]
    lines = [
        "# Parameter accounting",
        "",
        "Generated by `python scripts/parameter_accounting.py` by instantiating the default (main-text) model. "
        "'Supp. Table 1' is the manuscript's Supplementary Table 1 as transcribed in `reporting/manuscript_reported_values.json`. "
        "This implementation is not expected to match Supplementary Table 1 exactly: that table includes modules the main text does not "
        "describe, and several of its per-row counts omit biases/LayerNorm parameters.",
        "",
        "| Component | This implementation | Supp. Table 1 | Difference |",
        "|---|---:|---:|---:|",
    ]
    for key, mine in counts.items():
        if key in SUPP_KEY:
            a, b = SUPP_KEY[key]
            ref = supp[a] if b is None else supp[a][b]
            lines.append(f"| {key} | {mine:,} | {ref:,} | {mine - ref:+,} |")
        else:
            lines.append(f"| {key} | {mine:,} | - (learned text prompts; not in Supp. Table 1) | n/a |")
    for key in ONLY_IN_SUPP:
        ref = supp["components"][key]
        lines.append(f"| {key} | 0 (not in main text) | {ref:,} | {-ref:+,} |")
    trainable = sum(v for k, v in counts.items() if k != "frozen_backbone")
    s_tr, s_total = sum(supp["components"].values()), sum(supp["components"].values()) + supp["frozen_backbone"]
    lines += [
        "",
        f"- **Trainable (this implementation):** {trainable:,}  |  Supp. Table 1: {s_tr:,}  |  manuscript text: ~18.3 M",
        f"- **Total (this implementation):** {trainable + counts['frozen_backbone']:,}  |  Supp. Table 1: {s_total:,}  |  manuscript text: ~104.6 M",
        "",
        "The LoRA row is exact (589,824) and the three MS-VLE cross-attention blocks match the table's 393,216 each. "
        "Frozen-backbone count differs because Supp. Table 1 omits biases and LayerNorms for the transformer blocks.",
        "",
    ]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    sys.exit(main())
